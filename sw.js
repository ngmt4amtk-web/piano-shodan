async function cleanScores() {
  const scores = await caches.open(SVG_CACHE);
  for (const path of svgPaths)
    if (!(await scores.match(new URL(path, base)))) return;
  for (const key of await caches.keys())
    if (key.startsWith("piano-shodan-svg-") && key !== SVG_CACHE)
      await caches.delete(key);
}
