function activateWhenSafe() {
  if (!activation) activation = (async () => {
    const clients = await self.clients.matchAll({ includeUncontrolled: true, type: 'window' });
    const busy = await Promise.all(clients.map(client => new Promise(resolve => {
      const channel = new MessageChannel();
      const timer = setTimeout(() => { channel.port1.close(); resolve(false); }, 700);
      channel.port1.onmessage = event => {
        clearTimeout(timer); channel.port1.close();
        resolve(event.data?.busy === true);
      };
      client.postMessage({ type: 'update-ready' }, [channel.port2]);
    })));
    if (!busy.some(Boolean)) await self.skipWaiting();
  })().finally(() => { activation = null; });
  return activation;
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(VERSION);
      for (const path of required) {
        const response = await fetch(new URL(path, base), { cache: "reload" });
        if (!response.ok) throw Error(path);
        await cache.put(new URL(path, base), response);
      }
      await cache.put(base, await cache.match(new URL("./index.html", base)));
      // On updates, keep the active worker (and its data) until every new
      // score is available. Shell-only updates reuse the data-version cache.
      if ((await caches.keys()).some((key) => key.startsWith("piano-shodan-") && key !== VERSION)) {
        const scores = await caches.open(SVG_CACHE);
        for (const path of svgPaths) {
          const url = new URL(path, base);
          if (await scores.match(url)) continue;
          const response = await fetch(url, { cache: "reload" });
          if (!response.ok) throw Error(path);
          await scores.put(url, response);
        }
      }
      // v3 questions/performance defer activation; v2's unchanged legacy
      // registration cannot reply, so skipWaiting + claim releases its shell.
      await activateWhenSafe();
    })(),
  );
});
self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key.startsWith("piano-shodan-") && !key.startsWith("piano-shodan-svg-") && key !== VERSION)
          await caches.delete(key);
      }
      await cleanScores();
      await self.clients.claim();
    })(),
  );
});
self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  if (
    event.request.method !== "GET" ||
    url.origin !== base.origin ||
    !url.pathname.startsWith(base.pathname) ||
    url.pathname.includes("/api/")
  )
    return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(assetCache(url.pathname)),
        cached = await cache.match(event.request, { ignoreSearch: true });
      if (cached) return cached;
      const response = await fetch(event.request);
      if (response.ok) await cache.put(event.request, response.clone());
      return response;
    })(),
  );
});
